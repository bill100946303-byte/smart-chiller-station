const otherPageNamespacePattern = /\.(?:dashboard|cockpit|device|scene|project|system|energy|ai|performance|report|trend|meter|hvac|fcu|cold-log|cold-station|environment|power|operation|operational|knowledge|config|optimize)(?:-|\b)/;
const generatedMarker = "Generated by scripts/split-page-css.mjs";

function classifyRule(rule) {
  const selectors = rule.selectors || [rule.selector];
  for (const target of targets) {
    const belongsToTarget = selectors.every((selector) => {
      if (!target.selectorPattern.test(selector)) {
        return false;
      }
      const targetRemoved = selector.replace(new RegExp(target.selectorPattern.source, "g"), "");
      return !otherPageNamespacePattern.test(targetRemoved);
    });
    if (belongsToTarget) {
      return target.key;
    }
  }
  return "global";
}

function splitContainer(container) {
  const buckets = new Map([["global", []], ...targets.map((target) => [target.key, []])]);

  for (const child of container.nodes || []) {
    if (child.type === "rule") {
      buckets.get(classifyRule(child)).push(child.clone());
      continue;
    }

    if (Array.isArray(child.nodes)) {
      const nested = splitContainer(child);
      for (const [bucket, nodes] of nested.entries()) {
        if (nodes.length === 0) {
          continue;
        }
        const clonedContainer = child.clone();
        clonedContainer.removeAll();
        clonedContainer.append(nodes);
        buckets.get(bucket).push(clonedContainer);
      }
      continue;
    }

    // Comments, imports, custom properties and standalone at-rules remain global.
    buckets.get("global").push(child.clone());
  }

  return buckets;
}

function createRoot(nodes, header = null) {
  const root = postcss.root();
  if (header) {
    root.append(postcss.comment({ text: header }));
  }
  root.append(nodes);
  return `${root.toString().trim()}\n`;
}

function analyze(root) {
  const counts = Object.fromEntries(targets.map((target) => [target.key, { rules: 0, bytes: 0 }]));
  root.walkRules((rule) => {
    const bucket = classifyRule(rule);
    if (bucket === "global") {
      return;
    }
    counts[bucket].rules += 1;
    counts[bucket].bytes += rule.toString().length;
  });
  return counts;
}

const mode = process.argv[2] || "--analyze";
const source = fs.readFileSync(globalCssPath, "utf8");
const parsed = postcss.parse(source, { from: globalCssPath });
const counts = analyze(parsed);

if (mode === "--analyze") {
  console.log(JSON.stringify({ globalBytes: Buffer.byteLength(source), extractable: counts }, null, 2));
  process.exit(0);
}

if (mode === "--resplit") {
  const requestedKeys = process.argv.slice(3);
  const requestedTargets = targets.filter((target) => requestedKeys.includes(target.key));
  if (requestedTargets.length !== requestedKeys.length || requestedTargets.length === 0) {
    throw new Error(`Unknown or missing resplit target: ${requestedKeys.join(", ")}`);
  }

  let combinedSource = source;
  for (const target of requestedTargets) {
    const existing = fs.readFileSync(target.outputPath, "utf8");
    const withoutHeader = existing.replace(/^\/\* Generated by scripts\/split-page-css\.mjs[^\n]*\*\/\s*/, "");
    combinedSource += `\n${withoutHeader}`;
  }

  const combinedRoot = postcss.parse(combinedSource, { from: globalCssPath });
  const buckets = splitContainer(combinedRoot);
  const unexpected = targets
    .filter((target) => !requestedKeys.includes(target.key))
    .filter((target) => buckets.get(target.key).length > 0);
  if (unexpected.length > 0) {
    throw new Error(`Resplit would modify unrelated targets: ${unexpected.map((target) => target.key).join(", ")}`);
  }

  fs.writeFileSync(globalCssPath, createRoot(buckets.get("global")), "utf8");
  for (const target of requestedTargets) {
    const header = `${generatedMarker}. Pure ${target.key} selectors extracted from global.css; keep page-local.`;
    fs.writeFileSync(target.outputPath, createRoot(buckets.get(target.key), header), "utf8");
  }
  console.log(JSON.stringify({
    resplit: requestedKeys,
    globalBytes: fs.statSync(globalCssPath).size,
    outputs: Object.fromEntries(requestedTargets.map((target) => [target.key, fs.statSync(target.outputPath).size]))
  }, null, 2));
  process.exit(0);
}

if (mode === "--check") {
  const remainingRules = Object.values(counts).reduce((sum, item) => sum + item.rules, 0);
  const missingOutputs = targets.filter((target) => !fs.existsSync(target.outputPath));
  if (remainingRules > 0 || missingOutputs.length > 0) {
    console.error(JSON.stringify({ remainingRules, counts, missingOutputs: missingOutputs.map((item) => item.outputPath) }, null, 2));
    process.exit(1);
  }
  console.log("CSS page-module boundary check passed.");
  console.log(`- global.css: ${Buffer.byteLength(source)} bytes`);
  console.log(`- pure ${targets.map((target) => target.key).join("/")} rules no longer remain in global.css`);
  process.exit(0);
}

if (mode !== "--apply") {
  throw new Error(`Unsupported mode: ${mode}`);
}

const applicableTargets = targets.filter((target) => counts[target.key].rules > 0);

for (const target of applicableTargets) {
  if (fs.existsSync(target.outputPath)) {
    const existing = fs.readFileSync(target.outputPath, "utf8");
    if (existing.includes(generatedMarker)) {
      throw new Error(`Refusing to re-split an already generated module: ${target.outputPath}`);
    }
    throw new Error(`Refusing to overwrite an existing stylesheet: ${target.outputPath}`);
  }
}

const buckets = splitContainer(parsed);
fs.writeFileSync(globalCssPath, createRoot(buckets.get("global")), "utf8");
for (const target of targets) {
  if (!applicableTargets.includes(target)) {
    continue;
  }
  const header = `${generatedMarker}. Pure ${target.key} selectors extracted from global.css; keep page-local.`;
  fs.writeFileSync(target.outputPath, createRoot(buckets.get(target.key), header), "utf8");
}

