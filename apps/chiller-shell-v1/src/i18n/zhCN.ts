const localePacks: Record<LocaleCode, CopyPack> = {
  "zh-CN": zhBase,
  "en-US": deepMerge(zhBase, enOverrides) as CopyPack,
  "vi-VN": deepMerge(zhBase, viOverrides) as CopyPack
};

export function getCurrentLocale(): LocaleCode {
  if (typeof window === "undefined") {
    return DEFAULT_LOCALE;
  }
  return resolveLocaleCode(window.localStorage.getItem(LOCALE_STORAGE_KEY));
}

export function setCurrentLocale(locale: LocaleCode): void {
  if (typeof window === "undefined") {
    return;
  }
  window.localStorage.setItem(LOCALE_STORAGE_KEY, locale);
}

export function getLocalePack(locale?: LocaleCode): CopyPack {
  const resolved = locale || getCurrentLocale();
  return localePacks[resolved];
}

export function getLocaleOptions(): Array<{ value: LocaleCode; label: string }> {
  const pack = getLocalePack();
  return [
    { value: "zh-CN", label: pack.appShell.localeChinese },
    { value: "en-US", label: pack.appShell.localeEnglish },
    { value: "vi-VN", label: pack.appShell.localeVietnamese }
  ];
}

