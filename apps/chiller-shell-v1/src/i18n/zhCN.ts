export type LocaleCode = "zh-CN" | "en-US" | "vi-VN";

export const LOCALE_STORAGE_KEY = "chiller.locale";
const DEFAULT_LOCALE: LocaleCode = "zh-CN";

function resolveLocaleCode(value: string | null | undefined): LocaleCode {
  if (value === "en-US" || value === "vi-VN" || value === "zh-CN") {
    return value;
  }
  return DEFAULT_LOCALE;
}

function isPlainObject(value: unknown): value is Record<string, unknown> {
  return Object.prototype.toString.call(value) === "[object Object]";
}

function deepMerge<T>(base: T, override: Partial<T>): T {
  const output: Record<string, unknown> = { ...(base as Record<string, unknown>) };
  Object.entries(override as Record<string, unknown>).forEach(([key, value]) => {
    const baseValue = output[key];
    if (isPlainObject(baseValue) && isPlainObject(value)) {
      output[key] = deepMerge(baseValue, value);
      return;
    }
    output[key] = value;
  });
  return output as T;
}

